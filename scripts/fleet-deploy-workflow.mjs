const REVERT_MESSAGE = (sha, url) => `revert: restore the previous deploy workflow

The keyless workflow from ${sha.slice(0, 7)} failed before deploying (${url}), so
the app still serves its previous build. Restored by
freeappstore-online/platform scripts/fleet-deploy-workflow.mjs.

Refs freeappstore-online/platform#460, freeappstore-online/platform#523

Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>`;

/** Steps the legacy generators emitted; anything else is a creator's own. */
const KNOWN_STEPS = new Set([
  'Install',
  'Build',
  'Verify build output',
  'Write build info',
  'Upload to R2',
  'Verify route',
  'Code health scan',
  'Upload code health',
  'Resolve build target',
  'Typecheck (when configured)',
  'Tests (when configured)',
  'Retain verified dependency lock',
  'Upload build artifact',
  'Upload code health report',
  'Download build artifact',
  'Download code health report',
  'Upload keylessly',
]);
const KNOWN_ACTIONS =
  /^(actions\/checkout|pnpm\/action-setup|actions\/setup-node|actions\/upload-artifact|actions\/download-artifact)@/;
const KNOWN_ENV = new Set([
  'BUILD_COMMAND',
  'DEPLOY_API',
  'VITE_APP_VERSION',
  'VITE_COMMIT_SHA',
  'VITE_BUILD_DATE',
  'AWS_ACCESS_KEY_ID',
  'AWS_SECRET_ACCESS_KEY',
  'AWS_DEFAULT_REGION',
  'R2_ACCOUNT_ID',
  'OUTPUT_PATH',
]);
const R2_SECRETS = new Set(['R2_ACCESS_KEY_ID', 'R2_SECRET_ACCESS_KEY', 'R2_ACCOUNT_ID']);
const SYNC_SOURCES = new Set(['./web/dist', 'web/dist', '"$OUTPUT_PATH"']);

/** Variants whose workflow hard-codes `pnpm build` → web/dist (fas.json's defaults). */
const LEGACY_DEFAULTS = new Set([
  'legacy-minimal',
  'legacy-vcqa',
  'legacy-route',
  'legacy-route-buildinfo',
]);

/** The fas.json that states what a legacy workflow did implicitly. */
export function fasJsonFor(repo) {
  return `${JSON.stringify({ appId: repo, applicationRoot: 'web', outputPath: 'web/dist', buildCommand: 'pnpm build' }, null, 2)}\n`;
}

const uncommented = (text) => text.replace(/^\s*#.*$/gm, '');

/**
 * The deploy shape a workflow has, and why it needs hand review (empty when the
 * generator reproduces everything it does). Exported for the tests.
 */
export function classify(text, generated) {
  if (text == null) return { variant: 'no-deploy-yml', review: ['no deploy.yml'] };
  if (text === generated) return { variant: 'current', review: [] };
  let wf;
  try {
    wf = parse(text);
  } catch (error) {
    return { variant: 'custom', review: [`unparseable YAML: ${error.message}`] };
  }
  const code = uncommented(text);
  const review = [];
  const jobs = Object.entries(wf?.jobs ?? {});
  const steps = jobs.flatMap(([, job]) => job.steps ?? []);
  const secrets = new Set([...code.matchAll(/secrets\.(\w+)/g)].map((m) => m[1]));
  const extraSecrets = [...secrets].filter((s) => !R2_SECRETS.has(s));
  if (extraSecrets.length) review.push(`secrets ${extraSecrets.join(',')}`);
  if (/\$\{\{\s*vars\./.test(code)) review.push('repo variables');
  if (/wrangler|CLOUDFLARE_/.test(code)) review.push('wrangler/Cloudflare token');
  const triggers = Object.keys(wf?.on ?? {})
    .sort()
    .join(',');
  if (triggers !== 'push,workflow_dispatch') review.push(`triggers ${triggers}`);
  for (const step of steps) {
    if (step.uses && !KNOWN_ACTIONS.test(step.uses)) review.push(`action ${step.uses}`);
    if (!step.uses && !KNOWN_STEPS.has(step.name)) review.push(`step "${step.name ?? step.run}"`);
    for (const key of Object.keys(step.env ?? {}))
      if (!KNOWN_ENV.has(key)) review.push(`env ${key}`);
    if (step.name === 'Build' && step.run && !/^pnpm build$|BUILD_COMMAND/.test(step.run.trim()))
      review.push(`build command "${step.run.trim()}"`);
  }
  for (const [, source] of code.matchAll(/aws s3 sync (\S+)/g))
    if (!SYNC_SOURCES.has(source)) review.push(`syncs ${source}`);
  const has = (name) => steps.some((s) => s.name === name);
  if (!/aws s3 sync/.test(code) && !has('Upload keylessly')) review.push('no R2 sync');
  const variant = has('Upload keylessly')
    ? 'keyless-outdated'
    : jobs.length === 2 && jobs.some(([, j]) => j.needs)
      ? 'two-job-r2'
      : has('Resolve build target')
        ? 'pinned-single-job'
        : has('Verify route')
          ? has('Write build info')
            ? 'legacy-route-buildinfo'
            : 'legacy-route'
          : has('Code health scan')
            ? 'legacy-vcqa'
            : 'legacy-minimal';
  return { variant, review: [...new Set(review)] };
}

function sh(cmd, args, opts = {}) {
  return execFileSync(cmd, args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], ...opts });
}

function tryRun(cmd, args, opts) {
  try {
    return { ok: true, out: sh(cmd, args, opts) };
  } catch (error) {
    return { ok: false, out: `${error.stdout ?? ''}${error.stderr ?? ''}`.trim() };
  }
}

async function status(url) {
  try {
    return (await fetch(url, { redirect: 'manual', signal: AbortSignal.timeout(15000) })).status;
  } catch {
    return 0;
  }
}

/** Clone, classify and validate one repo. Leaves the clone for --apply. */
async function inspect(repo, generated, workdir) {
  const dir = join(workdir, repo);
  rmSync(dir, { recursive: true, force: true });
  sh('gh', ['repo', 'clone', `${ORG}/${repo}`, dir, '--', '--depth', '1', '--quiet']);
  const path = join(dir, WORKFLOW);
  const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
  const { variant, review } = classify(current, generated);
  const otherR2 = tryRun('git', [
    '-C',
    dir,
    'grep',
    '-l',
    'secrets\\.R2_',
    '--',
    '.github/workflows',
  ])
    .out.split('\n')
    .filter((f) => f && f !== WORKFLOW);
  if (otherR2.length) review.push(`R2 secrets also in ${otherR2.join(',')}`);
  // The legacy workflows built `pnpm build` into web/dist, which are fas.json's
  // defaults; without the file the validator falls back to the package name.
  // Pin the deployment id so the generated build job resolves the same target.
  const fasJson = join(dir, 'fas.json');
  const addFasJson = !existsSync(fasJson) && LEGACY_DEFAULTS.has(variant);
  if (addFasJson) writeFileSync(fasJson, fasJsonFor(repo));
  const preflight = tryRun(
    'node',
    [join(ROOT, 'packages/cli/dist/index.js'), 'build-target', '--app-id', repo],
    { cwd: dir },
  );
  if (!preflight.ok) review.push(`build-target: ${preflight.out.split('\n').at(-1)}`);
  const live = await status(`https://${repo}.freeappstore.online/`);
  if (live !== 200) review.push(`site returns ${live}`);
  const action = variant === 'current' ? 'skip' : review.length ? 'review' : 'update';
  return {
    repo,
    dir,
    variant: addFasJson ? `${variant}+fas.json` : variant,
    action,
    review,
    addFasJson,
  };
}

async function waitForDeploy(repo, sha) {
  for (let i = 0; i < 90; i++) {
    const runs = JSON.parse(
      sh('gh', [
        'run',
        'list',
        '--repo',
        `${ORG}/${repo}`,
        '--commit',
        sha,
        '--workflow',
        'deploy.yml',
        '--json',
        'databaseId,status,conclusion,url',
      ]),
    );
    const run = runs[0];
    if (run?.status === 'completed') return run;
    await new Promise((r) => setTimeout(r, 20000));
  }
  return { conclusion: 'timeout' };
}

async function apply(plan, generated, wait) {
  const { repo, dir } = plan;
  mkdirSync(join(dir, '.github/workflows'), { recursive: true });
  writeFileSync(join(dir, WORKFLOW), generated);
  sh('git', ['-C', dir, 'add', WORKFLOW, ...(plan.addFasJson ? ['fas.json'] : [])]);
  sh('git', ['-C', dir, 'commit', '--quiet', '-m', COMMIT_MESSAGE]);
  if (!tryRun('git', ['-C', dir, 'push', '--quiet', 'origin', 'HEAD:main']).ok) {
    sh('git', ['-C', dir, 'pull', '--rebase', '--quiet', 'origin', 'main']);
    sh('git', ['-C', dir, 'push', '--quiet', 'origin', 'HEAD:main']);
  }
  const sha = sh('git', ['-C', dir, 'rev-parse', 'HEAD']).trim();
  console.log(`${repo}: pushed ${sha.slice(0, 7)}`);
  if (!wait) return { ...plan, sha };
  const run = await waitForDeploy(repo, sha);
  const buildinfo = await status(`https://${repo}.freeappstore.online/.buildinfo.json`);
  const site = await status(`https://${repo}.freeappstore.online/`);
  if (run.conclusion === 'success')
    return {
      ...plan,
      sha,
      run: run.url,
      result:
        site === 200 && buildinfo === 200
          ? 'green'
          : `deployed; site ${site}, buildinfo ${buildinfo}`,
    };
  // The run failed before its commit switched the route (commit is its last
  // step), so the app still serves its legacy files: put the old workflow back.
  // Never revert once a keyless release has been live: the legacy sync's
  // --delete would remove the release the route serves.
  if (plan.variant.startsWith('keyless') || run.conclusion !== 'failure')
    return {
      ...plan,
      sha,
      run: run.url,
      result: `run ${run.conclusion}; not reverted, check by hand`,
    };
  sh('git', ['-C', dir, 'pull', '--rebase', '--quiet', 'origin', 'main']);
  sh('git', ['-C', dir, 'revert', '--no-commit', sha]);
  sh('git', ['-C', dir, 'commit', '--quiet', '-m', REVERT_MESSAGE(sha, run.url)]);
  sh('git', ['-C', dir, 'push', '--quiet', 'origin', 'HEAD:main']);
  return { ...plan, sha, run: run.url, result: `reverted (run ${run.conclusion})` };
}

function allAppRepos() {
  return sh('gh', [
    'repo',
    'list',
    ORG,
    '--limit',
    '1000',
    '--no-archived',
    '--json',
    'name',
    '--jq',
    '.[].name',
  ])
    .split('\n')
    .filter(
      (name) =>
        name && name !== 'platform' && !name.startsWith('template-') && !name.startsWith('.'),
    );
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const args = process.argv.slice(2);
  const applyChanges = args.includes('--apply');
  const wait = args.includes('--wait');
  const repos = args.includes('--all') ? allAppRepos() : args.filter((a) => !a.startsWith('--'));
  if (!repos.length) throw new Error('Name repos or pass --all');
  const { APP_STARTER_CONFIG, deployWorkflow } = await import(
    pathToFileURL(join(ROOT, 'packages/cli/dist/lib/starter-foundation.js'))
  );
  const generated = deployWorkflow(APP_STARTER_CONFIG);
  const workdir = join(tmpdir(), 'fas-fleet-deploy');
  mkdirSync(workdir, { recursive: true });
  const results = [];
  for (const repo of repos) {
    let plan;
    try {
      plan = await inspect(repo, generated, workdir);
    } catch (error) {
      plan = { repo, variant: 'error', action: 'review', review: [error.message.split('\n')[0]] };
    }
    if (applyChanges && plan.action === 'update') plan = await apply(plan, generated, wait);
    results.push(plan);
    console.log(
      [plan.repo, plan.variant, plan.action, plan.result ?? '', plan.review.join('; ')].join('\t'),
    );
  }
  const counts = {};
  for (const r of results)
    counts[`${r.variant}/${r.action}`] = (counts[`${r.variant}/${r.action}`] ?? 0) + 1;
  console.log(JSON.stringify(counts, null, 2));
  if (!applyChanges) console.log('Dry run: nothing pushed. Re-run with --apply [--wait].');
}
