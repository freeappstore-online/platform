// Fleet regeneration of app deploy workflows (#460, #523, #559).
//
// Rewrites `.github/workflows/deploy.yml` in freeappstore-online app repos from
// the one generator, deployWorkflow() in packages/cli (build `pnpm -r build` first):
// a caller of the platform's app-deploy.yml at the pinned commit, with the
// repo's own inputs from CALLER_INPUTS.
// Dry run by default: it clones each repo shallowly, classifies the current
// workflow, runs the build-target validator the new build job runs, and prints
// a plan. --apply commits and pushes straight to main; --wait then watches the
// Deploy run, checks the site, and reverts the commit if the run fails.
//
//   node scripts/fleet-deploy-workflow.mjs [--apply [--wait]] [--all | <repo>...]
//
// Idempotent: a repo whose workflow already equals the generator is skipped.
// Repos whose workflow carries anything the generator does not reproduce
// (other secrets, non-VITE repo variables, extra steps, triggers or paths) are
// listed for hand review and never rewritten, unless CALLER_INPUTS maps their
// extra steps to the platform workflow's inputs.

import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

