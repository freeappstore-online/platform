// Native derivatives of the vendored brand kit. Never redraw or modify brand/assets.
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const source = await readFile(resolve(root, 'brand/assets/favicon.svg'), 'utf8');
const mark = await readFile(resolve(root, 'brand/assets/mark.svg'), 'utf8');
const brand = JSON.parse(await readFile(resolve(root, 'brand/assets/brand.json'), 'utf8'));
assert.equal(brand.family, 'apps');
const desktopConfig = await readFile(resolve(root, 'desktop/electron-builder.yml'), 'utf8');
assert.match(desktopConfig, /mac:\n(?: {2}[^\n]*\n)* {2}icon: build\/icon-mac\.png/);
for (const name of ['ic_launcher.xml', 'ic_launcher_round.xml']) {
  const adaptiveXml = await readFile(
    resolve(root, `android/app/src/main/res/mipmap-anydpi/${name}`),
    'utf8',
  );
  assert.match(adaptiveXml, /<foreground android:drawable="@drawable\/ic_launcher_foreground"/);
  assert.match(adaptiveXml, /<monochrome android:drawable="@drawable\/ic_launcher_foreground"/);
}
const androidColors = await readFile(
  resolve(root, 'android/app/src/main/res/values/colors.xml'),
  'utf8',
);
assert.ok(
  androidColors
    .toLowerCase()
    .includes(`<color name="ic_launcher_background">${brand.accent.toLowerCase()}</color>`),
);
assert.match(source, /viewBox="0 0 64 64"/);
assert.equal(source.match(/<rect width="64" height="64" rx="14"/g)?.length, 1);
// Full-bleed native/store artwork: retain the canonical gradient and exact tile geometry.
const master = source.replace(
  '<rect width="64" height="64" rx="14"',
  '<rect width="64" height="64" rx="0"',
);
const tiles = [
  ...mark.matchAll(
    /<rect x="([\d.]+)" y="([\d.]+)" width="([\d.]+)" height="([\d.]+)" rx="([\d.]+)"\/>/g,
  ),
].map((match) => match.slice(1).map(Number));
assert.equal(tiles.length, 4, 'Review native adapters when the canonical symbol changes');
const paths = tiles.map(([x, y, w, h, r]) => {
  // Android's 108dp layer maps the same 64-unit composition onto its central 72dp.
  // All tile bounding corners must fit the conservative 66dp safe circle.
  for (const px of [x, x + w])
    for (const py of [y, y + h])
      assert.ok(Math.hypot(18 + px * 1.125 - 54, 18 + py * 1.125 - 54) <= 33);
  return `M${x + r},${y}h${w - 2 * r}a${r},${r} 0,0 1,${r} ${r}v${h - 2 * r}a${r},${r} 0,0 1,-${r} ${r}h-${w - 2 * r}a${r},${r} 0,0 1,-${r} -${r}v-${h - 2 * r}a${r},${r} 0,0 1,${r} -${r}z`;
});
const foreground = `<!-- Generated by scripts/native-assets.mjs from brand/assets/mark.svg. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <group android:translateX="18" android:translateY="18" android:scaleX="1.125" android:scaleY="1.125">
        <path android:fillColor="#FFFFFF"
            android:pathData="${paths.join('\n                ')}" />
    </group>
</vector>
`;
const render = (svg, size) =>
  sharp(Buffer.from(svg), { density: (size / 64) * 72 })
    .resize(size, size)
    .flatten({ background: '#ffffff' })
    .removeAlpha()
    .png()
    .toBuffer();
const png1024 = await render(master, 1024);
const canonical512 = await readFile(resolve(root, 'brand/assets/icon-512.png'));
// Play requires a 32-bit PNG; an opaque alpha channel preserves every canonical RGB pixel.
const png512 = await sharp(canonical512).ensureAlpha(1).png().toBuffer();
assert.deepEqual(
  await sharp(png512).removeAlpha().raw().toBuffer(),
  await sharp(canonical512).raw().toBuffer(),
);
assert.ok(png512.length <= 1024 * 1024);
const macMaster = `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024" role="img" aria-label="FreeAppStore"><g transform="translate(100 100) scale(12.875)">${source.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')}</g></svg>\n`;
const macPng = await sharp(Buffer.from(macMaster)).png().toBuffer();
for (const [bytes, size, alpha] of [
  [png1024, 1024, false],
  [png512, 512, true],
  [macPng, 1024, true],
]) {
  const metadata = await sharp(bytes).metadata();
  assert.equal(metadata.width, size);
  assert.equal(metadata.height, size);
  assert.equal(metadata.hasAlpha, alpha, 'Incorrect platform PNG alpha format');
  assert.equal(metadata.space, 'srgb');
}
assert.equal((await sharp(png512).stats()).isOpaque, true);
const macRaw = await sharp(macPng).raw().toBuffer();
let bounds = [1024, 1024, -1, -1];
for (let y = 0; y < 1024; y++)
  for (let x = 0; x < 1024; x++) {
    if (!macRaw[(y * 1024 + x) * 4 + 3]) continue;
    bounds = [
      Math.min(bounds[0], x),
      Math.min(bounds[1], y),
      Math.max(bounds[2], x),
      Math.max(bounds[3], y),
    ];
  }
assert.deepEqual(
  bounds,
  [100, 100, 923, 923],
  'Mac icon must retain symmetric 100px transparent margins',
);

const symbol = mark.match(/<g[^>]*>(.*)<\/g>/s)?.[1];
assert.ok(symbol);
const svgImage = (svg) => `data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}`;
const image = (svg, x, y, size, extra = '') =>
  `<image href="${svgImage(svg)}" x="${x}" y="${y}" width="${size}" height="${size}" ${extra}/>`;
const label = (text, x, y) =>
  `<text x="${x}" y="${y}" fill="#334155" font-family="sans-serif" font-size="17">${text}</text>`;
const adaptive = (background, ink) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="18 18 72 72"><rect width="108" height="108" fill="${background}"/><g transform="translate(18 18) scale(1.125)" fill="${ink}">${symbol}</g></svg>`;
const sheet = `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="660" viewBox="0 0 1200 660">
<defs><clipPath id="ios"><rect x="40" y="82" width="192" height="192" rx="42"/></clipPath><clipPath id="circle"><circle cx="820" cy="178" r="96"/></clipPath><clipPath id="theme"><rect x="952" y="82" width="192" height="192" rx="48"/></clipPath></defs>
<rect width="1200" height="660" fill="#f8fafc"/>
${label('FreeAppStore — native icon audit', 40, 38)}
${image(master, 40, 82, 192, 'clip-path="url(#ios)"')}${label('iOS · mask preview', 40, 315)}
${image(master, 268, 82, 192)}${label('Windows / Linux / stores', 268, 315)}
${image(macMaster, 496, 82, 192)}${label('macOS · padded ICNS', 496, 315)}
${image(adaptive(brand.accent, '#ffffff'), 724, 82, 192, 'clip-path="url(#circle)"')}${label('Android · circle', 724, 315)}
${image(adaptive('#dbeafe', '#1e3a8a'), 952, 82, 192, 'clip-path="url(#theme)"')}${label('Android · themed', 952, 315)}
<rect x="40" y="382" width="510" height="224" rx="18" fill="#ffffff"/><rect x="576" y="382" width="492" height="224" rx="18" fill="#0f172a"/>
${[16, 24, 32, 48, 64, 96].map((size, i) => image(macMaster, 62 + i * 76, 445, size)).join('')}
${[16, 24, 32, 48, 64, 96].map((size, i) => image(macMaster, 598 + i * 74, 445, size)).join('')}
${label('16 / 24 / 32 / 48 / 64 / 96px · macOS icon with transparent padding', 40, 638)}
</svg>\n`;
const outputs = new Map([
  ['brand/native-assets/app-icon-master.svg', Buffer.from(master)],
  ['brand/native-assets/app-icon-1024.png', png1024],
  ['brand/native-assets/mac-icon-master.svg', Buffer.from(macMaster)],
  ['brand/native-assets/mac-icon-1024.png', macPng],
  ['brand/native-assets/play-icon-512.png', png512],
  ['brand/native-assets/contact-sheet.svg', Buffer.from(sheet)],
  ['desktop/build/icon.png', png1024],
  ['desktop/build/icon-mac.png', macPng],
  ['ios/FreeAppStore/Assets.xcassets/AppIcon.appiconset/AppIcon-1024.png', png1024],
  ['android/app/src/main/res/drawable/ic_launcher_foreground.xml', Buffer.from(foreground)],
]);
const hashes = Object.fromEntries(
  [...outputs].map(([path, bytes]) => [path, createHash('sha256').update(bytes).digest('hex')]),
);
outputs.set(
  'brand/native-assets/manifest.json',
  Buffer.from(
    `${JSON.stringify({ brandVersion: brand.version, source: 'brand/assets/favicon.svg + mark.svg', renderer: { sharp: sharp.versions.sharp, vips: sharp.versions.vips, rsvg: sharp.versions.rsvg }, sha256: hashes }, null, 2)}\n`,
  ),
);
const stale = [];
for (const [path, bytes] of outputs) {
  const absolute = resolve(root, path);
  const current = await readFile(absolute).catch(() => null);
  if (current?.equals(bytes)) continue;
  stale.push(path);
  if (!check) {
    await mkdir(dirname(absolute), { recursive: true });
    await writeFile(absolute, bytes);
  }
}
if (check && stale.length) throw new Error(`Stale native assets: ${stale.join(', ')}`);
console.log(
  `Native icons: ${check ? 'verified' : `${stale.length} updated`}; Android safe zone, Mac transparent padding and platform PNG formats verified.`,
);
// Raster contact sheet is a review artifact; its labels use the host's sans-serif font.
if (!check) {
  await mkdir(resolve(root, 'build/native-assets'), { recursive: true });
  await sharp(Buffer.from(sheet))
    .png()
    .toFile(resolve(root, 'build/native-assets/contact-sheet.png'));
}
