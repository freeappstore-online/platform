INSERT OR IGNORE INTO app_repositories (app_id, repository_id, repository, pinned_at)
SELECT a.id, v.repository_id, 'freeappstore-online/' || v.name, CAST(strftime('%s', 'now') AS INTEGER) * 1000
  FROM v
  JOIN apps a ON a.id = v.name
 WHERE (a.store IS NULL OR a.store = 'apps')
   AND (a.repo IS NULL OR a.repo = ''
        OR lower(a.repo) IN ('freeappstore-online/' || v.name,
                             'https://github.com/freeappstore-online/' || v.name,
                             'https://github.com/freeappstore-online/' || v.name || '.git'));
