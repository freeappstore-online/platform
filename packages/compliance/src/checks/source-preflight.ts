import type { FileSource } from '../lib/file-source.js';
import { stripHtmlComments } from '../lib/strip.js';
import { readBuildTarget, validateBuildTarget } from './build-target.js';

/**
 * Push-time preflight over an app's SOURCE files (no build, no network), shared
 * by `fas publish`, VibeCode and MCP `update_files` so a creation path cannot
 * push an app that fails its own first deploy for a reason visible in the
 * files (#550). It covers what the CI gates (`build-target --artifact`,
 * generated typecheck/test steps) would otherwise catch only after the push:
 *
 *   1. a `scripts.test` that runs vitest while vitest is not installed,
 *   2. icons the manifest, `vite.config.*` or `<link>` tags declare that are
 *      neither committed under `public/` nor generated by a `pwa-assets`
 *      pipeline from an existing source image,
 *   3. the build target (`fas.json` appId, entry, build/upload alignment).
 */
export interface PreflightResult {
  ok: boolean;
  failures: string[];
}

type Pkg = {
  scripts?: Record<string, string>;
  dependencies?: Record<string, string>;
  devDependencies?: Record<string, string>;
};

async function readJson<T>(source: FileSource, path: string): Promise<T | null> {
  const raw = await source.read(path);
  if (raw === null) return null;
  try {
    return JSON.parse(raw) as T;
  } catch {
    return null;
  }
}

const hasDep = (pkg: Pkg | null, name: string) =>
  !!pkg && (name in (pkg.dependencies ?? {}) || name in (pkg.devDependencies ?? {}));

/** Names the pwa-assets-generator `minimal2023Preset` emits. */
const GENERATED_ICON =
  /^(?:favicon\.ico|apple-touch-icon-\d+x\d+\.png|pwa-\d+x\d+\.png|maskable-icon-\d+x\d+\.png)$/;

const IMAGE_EXT = /\.(?:png|svg|ico|webp|jpe?g|gif)$/i;

async function testScriptFailures(source: FileSource, root: string): Promise<string[]> {
  const rootPkg = await readJson<Pkg>(source, 'package.json');
  const failures: string[] = [];
  const dirs = root === '.' ? [''] : ['', `${root}/`];
  for (const dir of dirs) {
    const pkg = dir ? await readJson<Pkg>(source, `${dir}package.json`) : rootPkg;
    const test = pkg?.scripts?.test;
    if (test && /\bvitest\b/.test(test) && !hasDep(pkg, 'vitest') && !hasDep(rootPkg, 'vitest')) {
      failures.push(
        `${dir}package.json: scripts.test runs vitest but vitest is not in dependencies or devDependencies; add it or change the test script`,
      );
    }
  }
  return failures;
}

/** Local icon references from the manifest, vite config and index.html. */
async function declaredIcons(source: FileSource, root: string): Promise<Map<string, string>> {
  const refs = new Map<string, string>(); // public-relative path -> where declared
  const add = (ref: string | undefined, where: string) => {
    if (!ref || /^(?:[a-z][a-z0-9+.-]*:|\/\/)/i.test(ref)) return;
    const path = ref.split(/[?#]/)[0]!.replace(/^\/+/, '').replace(/^\.\//, '');
    if (path && IMAGE_EXT.test(path) && !refs.has(path)) refs.set(path, where);
  };
  const publicDir = root === '.' ? 'public' : `${root}/public`;
  for (const name of ['manifest.json', 'manifest.webmanifest']) {
    const manifest = await readJson<{ icons?: { src?: string }[] }>(source, `${publicDir}/${name}`);
    for (const icon of manifest?.icons ?? []) add(icon.src, `${publicDir}/${name}`);
  }
  const html = stripHtmlComments(
    (await source.read(root === '.' ? 'index.html' : `${root}/index.html`)) ?? '',
  );
  for (const tag of html.matchAll(/<link\b[^>]*>/gi)) {
    if (!/\brel\s*=\s*["'][^"']*\b(?:icon|apple-touch-icon)\b/i.test(tag[0])) continue;
    add(/\bhref\s*=\s*["']([^"']+)["']/i.exec(tag[0])?.[1], 'index.html <link>');
  }
  for (const config of ['vite.config.ts', 'vite.config.js', 'vite.config.mts', 'vite.config.mjs']) {
    const path = root === '.' ? config : `${root}/${config}`;
    const text = (await source.read(path)) ?? '';
    if (!/VitePWA/.test(text)) continue;
    for (const m of text.matchAll(/\bsrc\s*:\s*["']([^"']+)["']/g)) add(m[1], path);
  }
  return refs;
}

/** True when a configured `pwa-assets` pipeline generates icons at build time from an existing image. */
async function hasIconPipeline(source: FileSource, root: string): Promise<boolean> {
  const prefix = root === '.' ? '' : `${root}/`;
  for (const name of ['pwa-assets.config.ts', 'pwa-assets.config.js', 'pwa-assets.config.mjs']) {
    const config = await source.read(`${prefix}${name}`);
    if (config === null) continue;
    const images = /\bimages\s*:\s*\[([^\]]*)\]/.exec(config)?.[1] ?? '';
    const sources = [...images.matchAll(/["']([^"']+)["']/g)].map((m) => m[1]!);
    let sourceExists = false;
    for (const image of sources) {
      if ((await source.read(`${prefix}${image.replace(/^\.\//, '')}`)) !== null)
        sourceExists = true;
    }
    if (!sourceExists) continue;
    const pkg = await readJson<Pkg>(source, `${prefix}package.json`);
    const scripts = pkg?.scripts ?? {};
    const runsGenerator = (body: string | undefined, depth = 0): boolean =>
      !!body &&
      (/pwa-assets-generator/.test(body) ||
        (depth < 2 &&
          [...body.matchAll(/(?:pnpm|npm run|yarn)(?: run)?\s+([\w:-]+)/g)].some((m) =>
            runsGenerator(scripts[m[1]!], depth + 1),
          )));
    if (runsGenerator(scripts.build) || runsGenerator(scripts.prebuild)) return true;
  }
  return false;
}

async function iconFailures(source: FileSource, root: string): Promise<string[]> {
  const refs = await declaredIcons(source, root);
  if (refs.size === 0) return [];
  const publicDir = root === '.' ? 'public' : `${root}/public`;
  const generated = await hasIconPipeline(source, root);
  const failures: string[] = [];
  for (const [path, where] of refs) {
    const bytes = source.readBytes ? await source.readBytes(`${publicDir}/${path}`) : null;
    const present = source.readBytes
      ? !!bytes?.length
      : (await source.read(`${publicDir}/${path}`)) !== null;
    if (present) continue;
    if (generated && GENERATED_ICON.test(path)) continue;
    failures.push(
      `${where} declares icon /${path} but ${publicDir}/${path} is missing or empty and no pwa-assets pipeline generates it; commit the file or configure pwa-assets from an existing source image`,
    );
  }
  return failures;
}

export async function runSourcePreflight(
  source: FileSource,
  options: { expectedAppId?: string | undefined } = {},
): Promise<PreflightResult> {
  const failures: string[] = [];
  const target = await validateBuildTarget(source, { expectedAppId: options.expectedAppId });
  if (target.status === 'fail') failures.push(target.detail);
  let root = 'web';
  try {
    root = (await readBuildTarget(source)).applicationRoot;
  } catch {
    // The build-target failure above already explains it; fall back to the default root.
  }
  failures.push(...(await testScriptFailures(source, root)));
  failures.push(...(await iconFailures(source, root)));
  return { ok: failures.length === 0, failures };
}

/**
 * Why a `.github/workflows/deploy.yml` cannot deploy: it still reads the org R2
 * secrets (removed, #523), lacks the OIDC `id-token: write` grant, has no
 * `deploy` job, or runs its own steps instead of calling the platform deploy
 * workflow at a pinned commit (the API accepts no other, #559). Empty when it
 * can. Comments are ignored.
 */
export function workflowDeployProblems(text: string): string[] {
  const body = text.replace(/^\s*#.*$/gm, '');
  const problems: string[] = [];
  if (/secrets\.R2_/.test(body)) problems.push('reads secrets.R2_*, which are removed');
  if (!/id-token:\s*write/.test(body)) problems.push('lacks `id-token: write` for keyless deploys');
  if (!/^ {2}deploy:\s*$/m.test(body)) problems.push('has no `deploy` job');
  if (!PLATFORM_DEPLOY_CALL.test(body))
    problems.push(
      'does not call freeappstore-online/platform/.github/workflows/app-deploy.yml at a pinned commit',
    );
  return problems;
}

/** The deploy job's call of the platform workflow; the pinned commit is checked by the API. */
const PLATFORM_DEPLOY_CALL =
  /^ {4}uses:\s*freeappstore-online\/platform\/\.github\/workflows\/app-deploy\.yml@[0-9a-f]{40}\s*$/m;
