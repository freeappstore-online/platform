import { describe, expect, it } from 'vitest';
import { mapFileSource } from '../lib/file-source.js';
import { runSourcePreflight } from './source-preflight.js';

/** A small, valid app: committed icons, vitest installed, aligned build target. */
function app(over: Record<string, string | null> = {}) {
  const files = new Map<string, string>([
    ['fas.json', JSON.stringify({ appId: 'taskflow', applicationRoot: 'web' })],
    [
      'package.json',
      JSON.stringify({ name: 'taskflow', scripts: { build: 'pnpm --dir web build' } }),
    ],
    [
      'web/package.json',
      JSON.stringify({
        scripts: { build: 'vite build', test: 'vitest run' },
        devDependencies: { vitest: '^4' },
      }),
    ],
    [
      'web/index.html',
      '<link rel="icon" href="/icon.svg"><link rel="apple-touch-icon" href="/apple.png"><script type="module" src="/src/main.tsx"></script>',
    ],
    ['web/src/main.tsx', "import './App'; initApp({appId: 'taskflow'});"],
    ['web/src/App.tsx', 'export default () => null'],
    ['web/public/icon.svg', '<svg></svg>'],
    ['web/public/apple.png', 'png'],
    ['web/public/manifest.json', JSON.stringify({ icons: [{ src: '/icon.svg' }] })],
  ]);
  for (const [k, v] of Object.entries(over)) {
    if (v === null) files.delete(k);
    else files.set(k, v);
  }
  return mapFileSource(files);
}

const run = (source = app(), expectedAppId = 'taskflow') =>
  runSourcePreflight(source, { expectedAppId });

describe('runSourcePreflight', () => {
  it('passes a consistent app', async () => {
    expect(await run()).toEqual({ ok: true, failures: [] });
  });

  it('fails a test script that runs vitest when vitest is not installed', async () => {
    const r = await run(
      app({
        'web/package.json': JSON.stringify({
          scripts: { build: 'vite build', test: 'vitest run' },
        }),
      }),
    );
    expect(r.ok).toBe(false);
    expect(r.failures.join('\n')).toMatch(/web\/package\.json: scripts\.test runs vitest/);
  });

  it('accepts vitest installed at the workspace root', async () => {
    const r = await run(
      app({
        'web/package.json': JSON.stringify({
          scripts: { build: 'vite build', test: 'vitest run' },
        }),
        'package.json': JSON.stringify({
          scripts: { build: 'pnpm --dir web build' },
          devDependencies: { vitest: '^4' },
        }),
      }),
    );
    expect(r.ok).toBe(true);
  });

  it('fails an icon declared in the manifest that is not committed', async () => {
    const r = await run(
      app({ 'web/public/manifest.json': JSON.stringify({ icons: [{ src: '/pwa-512x512.png' }] }) }),
    );
    expect(r.failures.join('\n')).toMatch(/icon \/pwa-512x512\.png/);
  });

  it('fails an empty icon file and a <link> icon that is missing', async () => {
    const r = await run(app({ 'web/public/apple.png': '', 'web/public/icon.svg': null }));
    expect(r.failures.join('\n')).toMatch(/\/apple\.png/);
    expect(r.failures.join('\n')).toMatch(/\/icon\.svg/);
  });

  it('fails an icon declared in the VitePWA options', async () => {
    const r = await run(
      app({
        'web/vite.config.ts': "VitePWA({ manifest: { icons: [{ src: 'pwa-192x192.png' }] } })",
      }),
    );
    expect(r.failures.join('\n')).toMatch(/web\/vite\.config\.ts declares icon \/pwa-192x192\.png/);
  });

  const generated = {
    'web/public/manifest.json': JSON.stringify({ icons: [{ src: '/pwa-512x512.png' }] }),
    'web/pwa-assets.config.ts': "export default { images: ['public/icon.svg'] }",
  };

  it('accepts icons generated by a pwa-assets pipeline from an existing source image', async () => {
    const r = await run(
      app({
        ...generated,
        'web/package.json': JSON.stringify({
          scripts: {
            'generate:icons': 'pwa-assets-generator --manifest=false',
            build: 'pnpm generate:icons && vite build',
          },
        }),
      }),
    );
    expect(r).toEqual({ ok: true, failures: [] });
  });

  it('rejects generated icons when the build never runs the generator, or the source image is missing', async () => {
    const noRun = await run(app(generated));
    expect(noRun.ok).toBe(false);
    const noSource = await run(
      app({
        ...generated,
        'web/public/icon.svg': null,
        'web/package.json': JSON.stringify({
          scripts: { build: 'pwa-assets-generator && vite build' },
        }),
      }),
    );
    expect(noSource.failures.join('\n')).toMatch(/pwa-512x512\.png/);
  });

  it('ignores external and data icon URLs', async () => {
    const r = await run(
      app({
        'web/public/manifest.json': JSON.stringify({
          icons: [{ src: 'https://cdn.example/i.png' }],
        }),
      }),
    );
    expect(r.ok).toBe(true);
  });

  it('includes the build-target failure: fas.json appId must equal the target id', async () => {
    const r = await run(app(), 'other-app');
    expect(r.failures.join('\n')).toMatch(
      /fas\.json appId taskflow differs from deployment ID other-app/,
    );
  });

  it('reports every failure at once', async () => {
    const r = await run(
      app({
        'web/package.json': JSON.stringify({
          scripts: { build: 'vite build', test: 'vitest run' },
        }),
        'web/public/icon.svg': null,
      }),
      'other-app',
    );
    expect(r.failures.length).toBeGreaterThanOrEqual(3);
  });
});
