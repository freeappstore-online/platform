import { execFileSync, spawnSync } from 'node:child_process';
import { createReadStream, mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { createServer, type Server } from 'node:http';
import type { AddressInfo } from 'node:net';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { _electron, type ElectronApplication, expect, test } from '@playwright/test';
import { homeWindow } from './home.js';

// Contribute (#826, #837) with the real model, against a stand-in API: downloads the phones' Kokoro
// package (350 MB from sherpa-onnx's GitHub release, or FAS_E2E_MODEL_FILE served by the stand-in),
// so it runs only with FAS_E2E_MODEL=1. It closes the window before the jobs are claimed, so they
// are generated with no window open, as in the tray: one English, one Mandarin (`dialogue`, zh).
test.skip(!process.env.FAS_E2E_MODEL, 'set FAS_E2E_MODEL=1 to download and run the real model');
test.setTimeout(15 * 60_000);

const here = new URL('.', import.meta.url);
const SHOTS = process.env.FAS_SHOTS_DIR ?? 'test-results/shots';
const TEXT = 'Hello there. This narration was generated by the desktop app with its window closed.';
const ZH = '你好，世界。今天是2024年3月5日，天气很好，我们去公园散步吧！';
const MODEL_FILE = process.env.FAS_E2E_MODEL_FILE;
/** The two apps' sets and jobs: English for books, Mandarin for dialogue. */
const APPS = {
  books: { voice: 'af_heart', language: null, text: TEXT, job: 'j1' },
  dialogue: { voice: 'zf_xiaoxiao', language: 'zh', text: ZH, job: 'j2' },
} as const;
let api: Server;
let userData: string;
let electron: ElectronApplication;
const uploads: {
  appId: string;
  contentType: string;
  file: Buffer;
  meta: unknown;
  lease: string;
}[] = [];
const claims: Record<string, number> = { books: 0, dialogue: 0 };

function serveApi(): Promise<Server> {
  const server = createServer(async (req, res) => {
    const path = new URL(req.url ?? '/', 'http://x').pathname;
    const chunks: Buffer[] = [];
    for await (const chunk of req) chunks.push(chunk as Buffer);
    const send = (status: number, body?: unknown) =>
      res
        .writeHead(status, { 'content-type': 'application/json' })
        .end(body === undefined ? undefined : JSON.stringify(body));
    if (path === '/model.tar.bz2' && MODEL_FILE) return createReadStream(MODEL_FILE).pipe(res);
    if (req.headers.authorization !== 'Bearer ndev_e2e') return send(401, { error: 'no' });
    const set = (appId: keyof typeof APPS) => ({
      setId: `s-${appId}`,
      kind: 'tts',
      model: 'kokoro',
      modelVersion: 'v1.0',
      params: { voice: APPS[appId].voice },
      formats: ['audio/mp4'],
      maxBytes: 25_000_000,
      language: APPS[appId].language,
    });
    if (path === '/v1/generation/open')
      return send(200, {
        apps: (['books', 'dialogue'] as const).map((appId) => ({
          appId,
          oneliner: null,
          sets: [{ ...set(appId), open: 1 }],
        })),
      });
    const claim = /^\/v1\/apps\/(books|dialogue)\/generation\/claim$/.exec(path);
    if (claim) {
      const appId = claim[1] as keyof typeof APPS;
      if (claims[appId]!++ > 0) return send(204);
      return send(200, {
        job: {
          ...set(appId),
          id: APPS[appId].job,
          key: `e2e/${appId}`,
          input: { text: APPS[appId].text },
          leaseToken: `lease-${appId}`,
          leaseExpiresAt: Date.now() + 15 * 60_000,
        },
      });
    }
    const result = /^\/v1\/apps\/(books|dialogue)\/generation\/jobs\/j\d\/result$/.exec(path);
    if (result && req.method === 'PUT') {
      const form = await new Request('http://x', {
        method: 'PUT',
        headers: { 'content-type': req.headers['content-type']! },
        body: Buffer.concat(chunks),
      }).formData();
      const file = form.get('file') as File;
      uploads.push({
        appId: result[1]!,
        contentType: file.type,
        file: Buffer.from(await file.arrayBuffer()),
        meta: JSON.parse(String(form.get('meta'))),
        lease: String(req.headers['x-lease-token']),
      });
      return send(202, { submissionId: `x-${result[1]}`, status: 'pending' });
    }
    if (path.endsWith('/generation/events')) return send(200, { recorded: 1 });
    if (path.endsWith('/generation/submissions')) return send(200, { submissions: [] });
    send(404, { error: 'not found' });
  });
  return new Promise((resolve) => server.listen(0, '127.0.0.1', () => resolve(server)));
}

test.beforeAll(async () => {
  api = await serveApi();
  userData = mkdtempSync(join(tmpdir(), 'fas-contribute-e2e-'));
  writeFileSync(join(userData, 'device-token'), 'ndev_e2e', { mode: 0o600 });
  writeFileSync(
    join(userData, 'settings.json'),
    JSON.stringify({ paused: false, openAtLogin: false, contributeApps: ['books', 'dialogue'] }),
  );
  electron = await _electron.launch({
    args: ['.'],
    cwd: new URL('..', here).pathname,
    env: {
      ...process.env,
      FAS_DESKTOP_USER_DATA: userData,
      FAS_DESKTOP_PORT: '47899',
      FAS_DEV_API_ORIGIN: `http://127.0.0.1:${(api.address() as AddressInfo).port}`,
      ...(MODEL_FILE && {
        FAS_DEV_MODEL_URL: `http://127.0.0.1:${(api.address() as AddressInfo).port}/model.tar.bz2`,
      }),
    } as Record<string, string>,
  });
});

test.afterAll(async () => {
  await electron?.close();
  api?.close();
  rmSync(userData, { recursive: true, force: true });
});

test('downloads the model on request, then generates English and Mandarin with the window closed', async () => {
  const home = await homeWindow(electron);
  await home.getByRole('button', { name: 'Contribute', exact: true }).click();
  await expect(home.getByLabel('Generate for books')).toBeChecked();
  // Mandarin is tickable: the phones' engine speaks it (#837)
  await expect(home.getByLabel('Generate for dialogue')).toBeEnabled();
  await expect(
    home.getByText('Kokoro v1.0 (sherpa-onnx, CPU) · speaks English, Spanish, Mandarin'),
  ).toBeVisible();
  await expect(home.getByTestId('contribute-status')).toHaveText('Idle');
  await expect(home.getByText('Download the voice model to start.')).toBeVisible();
  expect(claims).toEqual({ books: 0, dialogue: 0 }); // nothing is claimed before the model is there
  await home.screenshot({ path: join(SHOTS, 'contribute.png') });
  await home.getByRole('button', { name: /^Download the model/ }).click();
  // Close the window as soon as the download starts: the rest happens in the background
  await expect(home.getByText(/^(Downloading|Unpacking) the model/)).toBeVisible();
  await electron.evaluate(({ BrowserWindow }) =>
    BrowserWindow.getAllWindows()
      .find((w) => w.isVisible())!
      .close(),
  );
  await expect.poll(() => uploads.length, { timeout: 14 * 60_000, intervals: [2000] }).toBe(2);
  expect(
    await electron.evaluate(({ BrowserWindow }) =>
      BrowserWindow.getAllWindows().some((w) => w.isVisible()),
    ),
  ).toBe(false);

  const out = join('test-results', 'uploads');
  mkdirSync(out, { recursive: true });
  for (const upload of uploads) {
    const app = APPS[upload.appId as keyof typeof APPS];
    expect(upload.contentType).toBe('audio/mp4');
    expect(upload.lease).toBe(`lease-${upload.appId}`);
    const segments = (upload.meta as { segments: number[][] }).segments;
    const split = upload.appId === 'books' ? 12 : 6; // after "Hello there." / "你好，世界。"
    expect(segments.map(([start, end]) => [start, end])).toEqual([
      [0, split],
      [upload.appId === 'books' ? 13 : 6, app.text.length],
    ]);
    // A real AAC track in MP4, as long as its timings say (kept for the backend's verdict check)
    const m4a = join(out, `${upload.appId}.m4a`);
    writeFileSync(m4a, upload.file);
    writeFileSync(
      join(out, `${upload.appId}.json`),
      JSON.stringify({ meta: upload.meta, text: app.text }),
    );
    const probe = JSON.parse(
      execFileSync('ffprobe', ['-v', 'quiet', '-print_format', 'json', '-show_streams', m4a], {
        encoding: 'utf8',
      }),
    ) as {
      streams: { codec_name: string; channels: number; duration: string; bit_rate: string }[];
    };
    const [stream] = probe.streams;
    expect([stream!.codec_name, stream!.channels]).toEqual(['aac', 1]);
    expect(Number(stream!.duration)).toBeCloseTo(segments.at(-1)![3]!, 0);
    // Speech, not silence: ffmpeg's mean volume of the decoded audio (it reports on stderr)
    const { stderr } = spawnSync('ffmpeg', ['-i', m4a, '-af', 'volumedetect', '-f', 'null', '-'], {
      encoding: 'utf8',
    });
    const mean = Number(/mean_volume: (-?[\d.]+) dB/.exec(stderr)?.[1]);
    expect(mean).toBeGreaterThan(-40);
    console.log(
      `${upload.appId}: ${upload.file.length} bytes, ${stream!.duration} s, ${stream!.bit_rate} b/s, mean ${mean} dB`,
    );
  }
});
